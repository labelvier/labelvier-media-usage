	public static function render(): void {
		if (!current_user_can(self::CAP)) {
			wp_die(esc_html__('You are not allowed to access this page.', 'labelvier-media-usage'), 403);
		}
		$repo    = new FileRepository();
		$state   = ScanState::get();
		$summary = $repo->summary();
		$filters = self::filters_from(wp_unslash($_GET));

		echo '<div class="wrap lvmu-wrap">';
		echo '<h1 class="wp-heading-inline">' . esc_html__('Media Usage', 'labelvier-media-usage') . '</h1><hr class="wp-header-end">';

		self::render_result_notice();
		echo '<div id="lvmu-jobs" class="lvmu-jobs">' . self::jobs_html() . '</div>'; // phpcs:ignore WordPress.Security.EscapeOutput
		$blocked = Deleter::disabled_reason();
		if ($blocked !== '') {
			echo '<div class="notice notice-warning inline lvmu-delete-disabled"><p>' . esc_html($blocked) . '</p></div>';
		}
		self::render_status($state, $summary);
		if ($summary['total']['count'] > 0) {
			self::render_summary($summary);
		}

		$table = new FilesListTable($filters);
		$table->prepare_items();

		echo '<div id="lvmu-files" class="lvmu-files">';
		echo '<h2 class="screen-reader-text">' . esc_html__('Files', 'labelvier-media-usage') . '</h2>';
		$table->views();
		$info = self::view_info($filters);
		if ($info) {
			echo '<div class="notice notice-info inline lvmu-view-info"><p><strong>' . esc_html($info[0]) . '</strong></p><p>' . esc_html($info[1]) . '</p></div>';
		}
		self::render_filters($filters, $table);

		echo '<form method="post" id="lvmu-bulk-form" action="' . esc_url(self::url()) . '">';
		foreach (self::filter_args($filters) as $k => $v) {
			echo '<input type="hidden" name="' . esc_attr($k) . '" value="' . esc_attr((string) $v) . '">';
		}
		$table->display();
		echo '</form>';
		echo '</div>';
		echo '</div>';
	}

	private static function render_result_notice(): void {
		if (isset($_GET['lvmu_started'])) {
			if ($_GET['lvmu_started'] === '1') {
				echo '<div class="notice notice-info is-dismissible"><p>' . esc_html__('Indexing started. This page updates automatically.', 'labelvier-media-usage') . '</p></div>';
			} else {
				echo '<div class="notice notice-warning is-dismissible"><p>' . esc_html__('Could not start indexing (already running or the scheduler is unavailable).', 'labelvier-media-usage') . '</p></div>';
			}
		}

		if (isset($_GET['lvmu_job_cancelled'])) {
			if ($_GET['lvmu_job_cancelled'] === '1') {
				echo '<div class="notice notice-success is-dismissible"><p>' . esc_html__('Scheduled deletion cancelled.', 'labelvier-media-usage') . '</p></div>';
			} else {
				echo '<div class="notice notice-warning is-dismissible"><p>' . esc_html__('The scheduled deletion could not be cancelled: it has already started or finished.', 'labelvier-media-usage') . '</p></div>';
			}
		}
		if (isset($_GET['lvmu_scheduled'])) {
			$job = DeleteQueue::get(absint($_GET['lvmu_scheduled']));
			if ($job) {
				/* translators: %s: number of files and size, like "12 files, 34 MB" */
				echo '<div class="notice notice-success is-dismissible"><p>' . esc_html(sprintf(__('Deletion of %s scheduled.', 'labelvier-media-usage'), $job['label'])) . '</p></div>';
			} else {
				echo '<div class="notice notice-warning is-dismissible"><p>' . esc_html__('Nothing was scheduled: no files selected, already scheduled, or deleting is disabled.', 'labelvier-media-usage') . '</p></div>';
			}
		}

		if (empty($_GET['lvmu_deleted'])) {
			return;
		}
		$key    = 'lvmu_delete_result_' . get_current_user_id();
		$result = get_transient($key);
		delete_transient($key);
		if (!is_array($result)) {
			return;
		}
		$class = $result['errors'] ? 'notice-warning' : 'notice-success';
		echo '<div class="notice ' . esc_attr($class) . ' is-dismissible lvmu-result"><p><strong>';
		/* translators: 1: number of files, 2: freed size */
		echo esc_html(sprintf(_n('Deleted %1$s file, freed %2$s.', 'Deleted %1$s files, freed %2$s.', (int) $result['deleted'], 'labelvier-media-usage'), number_format_i18n($result['deleted']), size_format((int) $result['freed'])));
		echo '</strong>';
		if (!empty($result['remaining'])) {
			/* translators: %s: number of files */
			echo ' ' . esc_html(sprintf(_n('%s more file was not processed in this request; repeat the action to continue.', '%s more files were not processed in this request; repeat the action to continue.', (int) $result['remaining'], 'labelvier-media-usage'), number_format_i18n($result['remaining'])));
		}
		echo '</p>';
		/* translators: %s: number of files */
		foreach (['skipped' => __('Skipped (%s)', 'labelvier-media-usage'), 'errors' => __('Errors (%s)', 'labelvier-media-usage')] as $k => $label) {
			if (empty($result[$k])) {
				continue;
			}
			echo '<details class="lvmu-details"><summary>' . esc_html(sprintf($label, number_format_i18n(count($result[$k])))) . '</summary><ul>';
			foreach (array_slice($result[$k], 0, 200) as $item) {
				echo '<li><code>' . esc_html($item['path']) . '</code> &mdash; ' . esc_html($item['reason']) . '</li>';
			}
			if (count($result[$k]) > 200) {
				echo '<li>&hellip;</li>';
			}
			echo '</ul></details>';
		}
		echo '</div>';
	}

	/** Notices for pending, running and recently finished delete jobs. */
	public static function jobs_html(): string {
		$jobs = DeleteQueue::jobs();
		uasort($jobs, static fn($a, $b) => $a['created_at'] <=> $b['created_at']);
		$out = '';
		$fmt = static fn($n) => number_format_i18n((int) $n);

		foreach ($jobs as $job) {
			$id   = (int) $job['id'];
			$user = get_userdata((int) $job['user_id']);
			$name = $user ? $user->user_login : __('unknown user', 'labelvier-media-usage');
			$size = size_format((int) $job['total_size']);
			/* translators: 1: number of files, 2: total size */
			$what = sprintf(_n('%1$s file (%2$s)', '%1$s files (%2$s)', (int) $job['count'], 'labelvier-media-usage'), $fmt($job['count']), $size);
			$link = static fn(string $action, string $label) => '<a href="' . esc_url(wp_nonce_url(self::url(['lvmu_action' => $action, 'job' => $id]), 'lvmu_job_' . $id)) . '">' . esc_html($label) . '</a>';

			if ($job['status'] === 'pending') {
				/* translators: 1: files and size, 2: relative time, 3: user name */
				$text = sprintf(__('Scheduled: delete %1$s — queued %2$s ago by %3$s', 'labelvier-media-usage'), $what, human_time_diff((int) $job['created_at']), $name);
				if ($job['note'] !== '') {
					$text .= ' (' . $job['note'] . ')';
				}
				$out .= '<div class="notice notice-warning inline lvmu-job"><p><span>' . esc_html($text) . '</span>';
				if (!$job['started_at']) {
					$out .= '<span class="lvmu-job__actions">' . $link('cancel_job', __('Cancel', 'labelvier-media-usage')) . '</span>';
				}
				$out .= '</p></div>';
			} elseif ($job['status'] === 'running') {
				/* translators: 1: files and size, 2: files done, 3: total files */
				$text = sprintf(__('Deleting %1$s: %2$s of %3$s done', 'labelvier-media-usage'), $what, $fmt($job['processed']), $fmt($job['count']));
				$out .= '<div class="notice notice-info inline lvmu-job"><p><span class="dashicons dashicons-update lvmu-spin" aria-hidden="true"></span><span>' . esc_html($text) . '</span></p></div>';
			} elseif ($job['status'] === 'done' || $job['status'] === 'failed') {
				if ((int) $job['finished_at'] < time() - DeleteQueue::RECENT) {
					continue;
				}
				$failed = $job['status'] === 'failed';
				$class  = $failed || $job['error_count'] ? 'notice-error' : 'notice-success';
				/* translators: 1: number of files, 2: freed size */
				$text = sprintf(_n('Deleted %1$s file, freed %2$s.', 'Deleted %1$s files, freed %2$s.', (int) $job['deleted'], 'labelvier-media-usage'), $fmt($job['deleted']), size_format((int) $job['freed']));
				if ($failed) {
					$text = __('Scheduled deletion failed.', 'labelvier-media-usage');
				}
				if ($job['skipped_count']) {
					/* translators: %s: number of files */
					$text .= ' ' . sprintf(__('Skipped: %s.', 'labelvier-media-usage'), $fmt($job['skipped_count']));
				}
				if ($job['error_count']) {
					/* translators: %s: number of files */
					$text .= ' ' . sprintf(__('Errors: %s.', 'labelvier-media-usage'), $fmt($job['error_count']));
				}
				$out .= '<div class="notice ' . $class . ' inline lvmu-job"><p><span>' . esc_html($text) . '</span><span class="lvmu-job__actions">' . $link('dismiss_job', __('Dismiss', 'labelvier-media-usage')) . '</span></p>';
				/* translators: %s: number of files */
				foreach (['skipped' => __('Skipped (%s)', 'labelvier-media-usage'), 'errors' => __('Errors (%s)', 'labelvier-media-usage')] as $k => $label) {
					if (!$job[$k]) {
						continue;
					}
					$out .= '<details class="lvmu-details"><summary>' . esc_html(sprintf($label, $fmt($job[$k === 'skipped' ? 'skipped_count' : 'error_count']))) . '</summary><ul>';
					foreach ($job[$k] as $item) {
						$out .= '<li>' . ($item['path'] !== '' ? '<code>' . esc_html($item['path']) . '</code> &mdash; ' : '') . esc_html($item['reason']) . '</li>';
					}
					if (count($job[$k]) < $job[$k === 'skipped' ? 'skipped_count' : 'error_count']) {
						$out .= '<li>&hellip;</li>';
					}
					$out .= '</ul></details>';
				}
				$out .= '</div>';
			}
		}
		return $out;
	}

	private static function render_status(array $state, array $summary): void {
		$running  = $state['status'] === 'running';
		$last     = self::last_indexed($state);
		$never = !$last && $summary['total']['count'] === 0;
		$payload = self::status_payload($state);

		if ($never && !$running) {
			echo '<div class="notice notice-warning inline"><p>' . esc_html__('The uploads folder has never been indexed. Click "Index now" to build the file index.', 'labelvier-media-usage') . '</p></div>';
		}
		if ($state['status'] === 'failed') {
			echo '<div class="notice notice-error inline"><p><strong>' . esc_html__('The last index run failed.', 'labelvier-media-usage') . '</strong> ' . esc_html($state['error']) . '</p></div>';
		}

		echo '<div class="lvmu-box lvmu-status">';
		echo '<div class="lvmu-status__info">';
		echo '<p class="lvmu-status__last"><span id="lvmu-status-icon" class="dashicons dashicons-update' . ($running ? ' lvmu-spin' : '') . '" aria-hidden="true"></span> ';
		echo '<span id="lvmu-status-line">' . esc_html($payload['line']) . '</span>';
		echo ' <span id="lvmu-status-date" class="description">' . esc_html($payload['line_date']) . '</span>';
		echo '</p>';

		echo '<div id="lvmu-progress" class="lvmu-progress" ' . ($running ? '' : 'hidden') . '>';
		echo '<p id="lvmu-progress-text" class="lvmu-progress__text" role="status" aria-live="polite">' . esc_html(self::progress_text($payload)) . '</p>';
		echo '<div class="lvmu-bar" role="progressbar" aria-label="' . esc_attr__('Indexing progress', 'labelvier-media-usage') . '" aria-valuemin="0" aria-valuemax="100" aria-valuenow="' . (int) $payload['percent'] . '"><span style="width:' . (int) $payload['percent'] . '%"></span></div>';
		echo '</div>';
		echo '<p class="description">' . esc_html__('Indexes automatically every night at 03:00 via Action Scheduler.', 'labelvier-media-usage') . '</p>';
		echo '</div>';

		echo '<form class="lvmu-status__actions" method="post" action="' . esc_url(admin_url('admin-post.php')) . '">';
		echo '<input type="hidden" name="action" value="lvmu_start_scan">';
		wp_nonce_field('lvmu_start_scan');
		if ($running) {
			echo '<input type="hidden" name="restart" value="1">';
			echo '<button type="submit" class="button" data-lvmu-restart>' . esc_html__('Restart index', 'labelvier-media-usage') . '</button>';
		} else {
			echo '<button type="submit" class="button button-primary">' . esc_html__('Index now', 'labelvier-media-usage') . '</button>';
		}
		echo '</form>';
		echo '</div>';
	}

	private static function progress_text(array $p): string {
		$text = $p['phase_label'] ? sprintf(
			/* translators: 1: step, 2: total steps, 3: phase label */
			__('Step %1$d of %2$d: %3$s', 'labelvier-media-usage'),
			$p['step'],
			$p['steps'],
			$p['phase_label']
		) : __('Starting…', 'labelvier-media-usage');
		if ($p['detail']) {
			$text .= ' — ' . $p['detail'];
		}
		return $text . ' (' . $p['percent'] . '%)';
	}

